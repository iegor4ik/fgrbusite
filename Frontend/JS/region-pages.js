const regionPageState = {
  currentRegion: null,
  modal: null
};

function getRegionPageData(regionId) {
  return regionPageData[regionId] || null;
}

function formatRegionDate(value) {
  if (!value) return '';
  try {
    return new Date(value).toLocaleDateString('uk-UA', { year: 'numeric', month: 'long', day: 'numeric' });
  } catch (e) {
    return value;
  }
}

function renderRegionPage(regionId) {
  const region = getRegionPageData(regionId);
  if (!region) return;

  document.title = `${region.title} — Федерація греко-римської боротьби України`;

  const heroTitle = document.getElementById('regionHeroTitle');
  const heroSubtitle = document.getElementById('regionHeroSubtitle');
  const regionName = document.getElementById('regionName');
  const regionDescription = document.getElementById('regionDescription');
  const regionImage = document.getElementById('regionHeroImage');
  const regionBadge = document.getElementById('regionBadge');
  const regionList = document.getElementById('regionPresidiumList');
  const modalTitle = document.getElementById('memberModalTitle');
  const modalRole = document.getElementById('memberModalRole');
  const modalPhoto = document.getElementById('memberModalPhoto');
  const modalDetails = document.getElementById('memberModalDetails');
  const modalBio = document.getElementById('memberModalBio');

  if (heroTitle) heroTitle.textContent = region.title;
  if (heroSubtitle) heroSubtitle.textContent = region.subtitle;
  if (regionName) regionName.textContent = region.title;
  if (regionDescription) regionDescription.textContent = region.description;
  if (regionBadge) regionBadge.textContent = region.bannerLabel;
  if (regionImage) regionImage.src = region.image;

  if (regionList) {
    regionList.innerHTML = '';
    region.members.forEach((member) => {
      const card = document.createElement('button');
      card.className = 'presidium-card';
      card.type = 'button';
      card.innerHTML = `
        <img class="presidium-card__photo" src="${member.photo}" alt="${member.fullName}" />
        <div class="presidium-card__name">${member.fullName}</div>
        <div class="presidium-card__role">${member.role}</div>
        <div class="presidium-card__meta">${member.phone || 'Контакт уточнюється'}</div>
      `;
      card.addEventListener('click', () => openMemberModal(member));
      regionList.appendChild(card);
    });
  }

  if (modalTitle && modalRole && modalPhoto && modalDetails && modalBio) {
    regionPageState.modal = {
      title: modalTitle,
      role: modalRole,
      photo: modalPhoto,
      details: modalDetails,
      bio: modalBio
    };
  }
}

